/* ============================================================================
 * build-datasets.mjs — generates every bundled dataset and the case-study
 * results that the executive summary quotes.
 *
 *   node tools/build-datasets.mjs
 *
 * Outputs:
 *   data/examples-2026.json   the five case studies (bars + metadata)
 *   data/demo-universe.json   the screener's bundled demo universe
 *   data/case-results.json    engine output + simulated outcome per case
 *   app/datasets.js           the same data as a browser global (QM_DATA)
 * ==========================================================================*/
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CAL, synth, idxOf } from './gen-datasets.mjs';
import { CASES, INDEX, UNIVERSE } from './scenarios.mjs';
import { simulateLong, simulateShort } from './simulate.mjs';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const QM = require(path.join(ROOT, 'app/engine.js'));

const PROVENANCE = {
  synthetic: true,
  generated: new Date().toISOString().slice(0, 10),
  window: { first: CAL[0], last: CAL[CAL.length - 1], sessions: CAL.length },
  note: 'These 322-session series were generated by tools/build-datasets.mjs to illustrate specific ' +
        'setups on the real NYSE trading calendar — they are not the price history of any company. ' +
        'Import real bars through the CSV tab to screen real candidates; see data/DATA.md.'
};

function build(def) {
  const bars = synth({ seed: def.seed, startPrice: def.startPrice, baseVolume: def.baseVolume, segments: def.segments });
  return { symbol: def.symbol, name: def.name, sector: def.sector, marketCap: def.marketCap,
           note: def.note, synthetic: true, bars };
}

/* ------------------------------------------------------------------ series */
const indexSeries = build(INDEX);
const caseSeries = CASES.map(build);
const universeSeries = UNIVERSE.map(build);

/* --------------------------------------------------- case-study evaluation */
function evaluateCase(def, series) {
  const bars = series.bars;
  const tIdx = idxOf(def.triggerDate);
  const upTo = bars.slice(0, tIdx + 1);                 // what a trader could see
  const f = QM.computeFeatures(upTo);
  const cfg = Object.assign({}, QM.DEFAULTS, { accountEquity: 100000, riskPctPerTrade: 0.5 });
  const regime = QM.regimeFromIndex(indexSeries.bars.slice(0, tIdx + 1));

  const setups = {
    breakout: QM.detectBreakout(f, cfg, null),
    ep: QM.detectEP(f, cfg, null),
    parabolic: QM.detectParabolic(f, cfg, { marketCap: def.marketCap })
  };
  const wanted = def.setupLabel.startsWith('Breakout') ? 'breakout'
               : def.setupLabel.startsWith('Episodic') ? 'ep' : 'parabolic';
  const setup = setups[wanted];

  // full-series MAs for the forward simulation
  const closes = bars.map(b => b.close);
  const ema10 = QM.ema(closes, 10), ema20 = QM.ema(closes, 20);
  const trigger = bars[tIdx];
  let trade = null, entry, stop;

  if (wanted === 'parabolic') {
    entry = trigger.vwapFail != null ? trigger.vwapFail : trigger.open;
    stop = trigger.high;
    trade = simulateShort(bars, { entryIdx: tIdx, entry, stop, ema10, ema20 });
  } else if (wanted === 'ep') {
    entry = trigger.orh;
    stop = trigger.orl;
    trade = simulateLong(bars, { entryIdx: tIdx, entry, stop, ema10, ema20, adr: f.adr });
    // an EP that loses its opening range on the gap day itself stops out same day
    if (trigger.low <= stop) {
      trade = { entry, stop, risk: entry - stop, side: 'long', mfeR: (trigger.high - entry) / (entry - stop),
                tranches: [{ date: trigger.date, frac: 1, price: stop, r: -1,
                             reason: 'lost the opening range the same session — stopped out intraday' }],
                totalR: -1, exitDate: trigger.date, outcome: 'loss', trailKey: 'ema10' };
    }
  } else {
    entry = setup.plan.entry;
    stop = trigger.low;
    if (trigger.high < entry) throw new Error(def.symbol + ': trigger bar never reached the entry');
    trade = simulateLong(bars, { entryIdx: tIdx, entry, stop, ema10, ema20, adr: f.adr });
  }

  const riskPct = Math.abs(entry - stop) / entry * 100;
  return {
    symbol: def.symbol, name: def.name, sector: def.sector, setupLabel: def.setupLabel,
    outcomeLabel: def.outcomeLabel, context: def.context, lesson: def.lesson,
    triggerDate: def.triggerDate, triggerIdx: tIdx, wanted,
    metrics: {
      price: f.price, adr: f.adr, dollarVol20: f.dollarVol20, avgVol20: f.avgVol20,
      ret1m: f.ret1m, ret3m: f.ret3m, ret6m: f.ret6m, pctOff52High: f.pctOff52High,
      rsi14: QM.last(f.rsi14), ema10: QM.last(f.ema10), ema20: QM.last(f.ema20),
      sma50: QM.last(f.sma50), sma200: QM.last(f.sma200)
    },
    setup: {
      type: setup.type, status: setup.status, eligible: setup.eligible, score: setup.score,
      pivot: setup.pivot, base: setup.base ? {
        startDate: setup.base.startDate, endDate: setup.base.endDate, len: setup.base.len,
        high: setup.base.high, low: setup.base.low, depthPct: setup.base.depthPct,
        depthCapPct: setup.base.depthCapPct, higherLows: setup.base.higherLows,
        lowsSlopePct: setup.base.lowsSlopePct, contraction: setup.base.contraction,
        volRatio: setup.base.volRatio, aboveSma50Frac: setup.base.aboveSma50Frac,
        nearEmaFrac: setup.base.nearEmaFrac, quality: setup.base.quality,
        leg: setup.base.leg
      } : null,
      gap: setup.gap, rvol: setup.rvol, baseRangePct: setup.baseRangePct,
      closeInRangePct: setup.closeInRangePct, priorRunPct: setup.priorRunPct,
      upDays: setup.upDays, bestMove: setup.bestMove, extensionAdr: setup.extensionAdr,
      peakDate: setup.peakDate, weakness: setup.weakness,
      checks: setup.checks, failing: setup.failing
    },
    allSetups: Object.fromEntries(Object.entries(setups).map(([k, v]) =>
      [k, { eligible: v.eligible, status: v.status || null, score: v.score || 0, reason: v.reason || null,
            failing: (v.failing || []).map(c => c.label) }])),
    justification: QM.justify(def.symbol, f, setup, cfg, null, regime),
    planText: QM.planText(def.symbol, f, setup),
    regime: regime,
    trade: { ...trade, entry, stop, riskPct, riskAdrMultiple: riskPct / f.adr }
  };
}

const caseResults = CASES.map((def, i) => evaluateCase(def, caseSeries[i]));

/* -------------------------------------------------------------- write out */
const examples = {
  provenance: PROVENANCE,
  cases: CASES.map((def, i) => ({
    symbol: def.symbol, name: def.name, sector: def.sector, marketCap: def.marketCap,
    setupLabel: def.setupLabel, outcomeLabel: def.outcomeLabel, triggerDate: def.triggerDate,
    context: def.context, lesson: def.lesson, bars: caseSeries[i].bars
  }))
};
const demo = {
  provenance: PROVENANCE,
  index: indexSeries,
  universe: [...caseSeries, ...universeSeries].map(s => ({
    symbol: s.symbol, name: s.name, sector: s.sector, marketCap: s.marketCap,
    note: s.note, synthetic: true, bars: s.bars
  }))
};

fs.mkdirSync(path.join(ROOT, 'data'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'data/examples-2026.json'), JSON.stringify(examples));
fs.writeFileSync(path.join(ROOT, 'data/demo-universe.json'), JSON.stringify(demo));
fs.writeFileSync(path.join(ROOT, 'data/case-results.json'), JSON.stringify(caseResults, null, 2));

const js = '/* GENERATED by tools/build-datasets.mjs — do not edit by hand.\n' +
  ' * SYNTHETIC demo data; see data/DATA.md for provenance and how to load real OHLCV. */\n' +
  'window.QM_DATA = ' + JSON.stringify({ provenance: PROVENANCE, index: demo.index,
                                         universe: demo.universe }) + ';\n';
fs.writeFileSync(path.join(ROOT, 'app/datasets.js'), js);

/* ------------------------------------------------------------- console log */
console.log(`calendar: ${CAL.length} sessions ${CAL[0]} -> ${CAL[CAL.length - 1]}`);
console.log(`regime at last bar: ${QM.regimeFromIndex(indexSeries.bars).label}`);
console.log('\ncase studies');
for (const r of caseResults) {
  console.log(`  ${r.symbol.padEnd(8)} ${r.setupLabel.padEnd(38)} ${r.triggerDate}` +
    `  eligible=${String(r.setup.eligible).padEnd(5)} status=${String(r.setup.status).padEnd(16)}` +
    ` score=${r.setup.score.toFixed(0).padStart(3)}` +
    `  risk=${r.trade.riskPct.toFixed(2)}% (${r.trade.riskAdrMultiple.toFixed(2)} ADR)` +
    `  result=${r.trade.totalR >= 0 ? '+' : ''}${r.trade.totalR.toFixed(2)}R  MFE=${r.trade.mfeR.toFixed(1)}R`);
  if (r.setup.failing.length) console.log('           failing: ' + r.setup.failing.map(c => c.label).join(' | '));
}
const scr = QM.screen(demo.universe, { indexBars: demo.index.bars, accountEquity: 100000, riskPctPerTrade: 0.5 });
console.log(`\nscreen of the demo universe as of ${CAL[CAL.length - 1]}: ` +
  `${scr.counts.eligible}/${scr.counts.universe} eligible ` +
  `(breakout ${scr.counts.breakout}, EP ${scr.counts.ep}, short ${scr.counts.parabolic})`);
for (const r of scr.results.filter(x => x.eligible)) {
  console.log(`  ${r.symbol.padEnd(8)} ${r.best.type.padEnd(10)} ${String(r.best.status).padEnd(16)}` +
    ` score=${r.score.toFixed(0).padStart(3)} entry=${QM.round(r.best.plan.entry, 2)} stop=${QM.round(r.best.plan.stop, 2)}` +
    ` risk=${QM.round(Math.abs(r.best.plan.riskPct), 2)}% (${QM.round(r.best.plan.adrMultiple, 2)} ADR)`);
}
console.log('\nrejected, with the first failing rule:');
for (const r of scr.results.filter(x => !x.eligible && x.f)) {
  const bo = r.setups.find(s => s.type === 'breakout');
  const first = (bo && bo.failing && bo.failing[0]) ? bo.failing[0].label : (bo && bo.reason) || 'n/a';
  console.log(`  ${r.symbol.padEnd(8)} ${first}`);
}
